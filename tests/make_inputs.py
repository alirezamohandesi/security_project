#!/usr/bin/env python3
"""Deterministically generate the recparse test corpus.

Every input described in ``SPECIFICATION.md`` section 8 is produced here so the
corpus can be regenerated byte-for-byte on any machine.  Run from anywhere:

    python3 tests/make_inputs.py
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

MAGIC = b"RECV1"
TEXT = 0x01
INT32 = 0x02
RAW = 0x03

OUT_DIR = Path(__file__).resolve().parent / "inputs"


def record(rec_type: int, payload: bytes, declared_len: int | None = None) -> bytes:
    """Build one record.  ``declared_len`` allows crafting truncated records."""
    length = len(payload) if declared_len is None else declared_len
    if not 0 <= length <= 255:
        raise ValueError(f"length {length} does not fit in a uint8")
    return bytes([rec_type, length]) + payload


def stream(count: int, *records: bytes) -> bytes:
    return MAGIC + bytes([count]) + b"".join(records)


def int32(value: int) -> bytes:
    return struct.pack("<i", value)


CORPUS: dict[str, bytes] = {
    # --- valid -----------------------------------------------------------
    "valid_empty": stream(0),
    "valid_text": stream(1, record(TEXT, b"hello world")),
    "valid_text24": stream(1, record(TEXT, b"payload of 24 bytes.....")),
    "valid_int32": stream(1, record(INT32, int32(-2))),
    "valid_raw": stream(1, record(RAW, bytes([0xDE, 0xAD, 0xBE, 0xEF]))),
    "valid_mixed": stream(
        3,
        record(TEXT, b"ok"),
        record(INT32, int32(1)),
        record(RAW, bytes([0x01, 0x02, 0x03])),
    ),
    # --- boundary --------------------------------------------------------
    # 31 bytes is the largest payload that fits alongside the NUL terminator.
    "boundary_text31": stream(1, record(TEXT, b"A" * 31)),
    # 32 bytes is one past the limit: invalid input, must be rejected.
    "boundary_text32": stream(1, record(TEXT, b"A" * 32)),
    "boundary_raw31": stream(1, record(RAW, bytes(range(1, 32)))),
    "boundary_raw32": stream(1, record(RAW, bytes(range(1, 33)))),
    # --- security reproducers -------------------------------------------
    "vuln_text_long": stream(1, record(TEXT, b"A" * 200)),
    "vuln_raw_long": stream(1, record(RAW, bytes([0x41]) * 200)),
    # --- invalid ---------------------------------------------------------
    "invalid_magic": b"XXXXX" + bytes([0]),
    "invalid_empty_file": b"",
    "invalid_truncated_header": stream(2, record(TEXT, b"ok")),
    # Declares 40 payload bytes but only supplies 4.
    "invalid_truncated_payload": stream(1, record(TEXT, b"abcd", declared_len=40)),
    "invalid_int32_len": stream(1, record(INT32, b"\x01\x02\x03")),
    "invalid_unknown_type": stream(1, record(0x09, b"zz")),
}


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, data in sorted(CORPUS.items()):
        path = OUT_DIR / f"{name}.bin"
        path.write_bytes(data)
        print(f"{path.name}: {len(data)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
